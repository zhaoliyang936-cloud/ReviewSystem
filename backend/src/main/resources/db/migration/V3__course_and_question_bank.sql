CREATE TABLE rs_subject (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id = 1),
    code VARCHAR(40) NOT NULL UNIQUE,
    name VARCHAR(100) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE rs_chapter (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    subject_id BIGINT NOT NULL DEFAULT 1 REFERENCES rs_subject(id),
    code VARCHAR(20) NOT NULL,
    name VARCHAR(100) NOT NULL,
    description TEXT NOT NULL DEFAULT '',
    sort_order INTEGER NOT NULL CHECK (sort_order >= 0),
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (subject_id, code),
    UNIQUE (subject_id, name)
);

CREATE TABLE rs_knowledge_point (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    subject_id BIGINT NOT NULL DEFAULT 1 REFERENCES rs_subject(id),
    chapter_id BIGINT NOT NULL REFERENCES rs_chapter(id),
    code VARCHAR(30) NOT NULL,
    name VARCHAR(120) NOT NULL,
    description TEXT NOT NULL DEFAULT '',
    sort_order INTEGER NOT NULL CHECK (sort_order >= 0),
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    version INTEGER NOT NULL DEFAULT 1 CHECK (version >= 1),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (subject_id, code),
    UNIQUE (chapter_id, name),
    UNIQUE (id, subject_id)
);

CREATE SEQUENCE rs_question_no_seq START WITH 1 INCREMENT BY 1 NO CYCLE;

CREATE TABLE rs_question (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    subject_id BIGINT NOT NULL DEFAULT 1 REFERENCES rs_subject(id),
    question_no VARCHAR(24) NOT NULL UNIQUE,
    origin VARCHAR(20) NOT NULL CHECK (origin IN ('MANUAL', 'AI_GENERATED')),
    status VARCHAR(16) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'SUSPENDED')),
    suspension_reason VARCHAR(500),
    current_version_id BIGINT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE rs_question_version (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    question_id BIGINT NOT NULL REFERENCES rs_question(id),
    version INTEGER NOT NULL CHECK (version >= 1),
    subject_id BIGINT NOT NULL DEFAULT 1 REFERENCES rs_subject(id),
    knowledge_point_id BIGINT,
    type VARCHAR(20) NOT NULL CHECK (type IN ('CHOICE', 'FILL', 'SHORT_ANSWER', 'ALGORITHM')),
    max_score NUMERIC(8,2) NOT NULL CHECK (max_score > 0),
    content_json JSONB NOT NULL,
    answer_json JSONB NOT NULL,
    rubric_json JSONB,
    source_ref VARCHAR(500),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (question_id, version),
    UNIQUE (id, question_id),
    FOREIGN KEY (knowledge_point_id, subject_id) REFERENCES rs_knowledge_point(id, subject_id)
);

ALTER TABLE rs_question ADD CONSTRAINT fk_rs_question_current_version
    FOREIGN KEY (current_version_id, id) REFERENCES rs_question_version(id, question_id);

CREATE TABLE rs_question_asset (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    question_version_id BIGINT NOT NULL REFERENCES rs_question_version(id),
    position INTEGER NOT NULL CHECK (position >= 0),
    storage_key VARCHAR(100) NOT NULL,
    mime VARCHAR(20) NOT NULL CHECK (mime IN ('image/png', 'image/jpeg')),
    size_bytes BIGINT NOT NULL CHECK (size_bytes > 0),
    width INTEGER NOT NULL CHECK (width > 0),
    height INTEGER NOT NULL CHECK (height > 0),
    sha256 CHAR(64) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (question_version_id, position)
);

CREATE TABLE rs_question_import_item (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    source_label VARCHAR(120) NOT NULL,
    source_question_no VARCHAR(120) NOT NULL,
    question_type VARCHAR(20) NOT NULL CHECK (question_type IN ('CHOICE', 'FILL', 'SHORT_ANSWER', 'ALGORITHM')),
    question_id BIGINT NOT NULL REFERENCES rs_question(id),
    imported_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (source_label, source_question_no, question_type)
);

CREATE INDEX rs_chapter_subject_sort_idx ON rs_chapter(subject_id, sort_order);
CREATE INDEX rs_kp_chapter_sort_idx ON rs_knowledge_point(chapter_id, sort_order);
CREATE INDEX rs_question_status_origin_idx ON rs_question(subject_id, status, origin);
CREATE INDEX rs_question_version_kp_type_idx ON rs_question_version(knowledge_point_id, type);
CREATE INDEX rs_question_asset_version_idx ON rs_question_asset(question_version_id);

